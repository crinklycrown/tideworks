const UML = { 'Ä': 'A', 'Ö': 'O', 'Ü': 'U' };
export function glyphText(set, text, x, y, col) {
  const x0 = x;
  for (const raw of String(text).toUpperCase()) {
    const ch = UML[raw] || raw, g = GLYPHS[ch];
    if (!g) { x += 4; continue; }
    g.forEach((r, j) => [...r].forEach((v, i) => { if (v === '1') set(x + i, y + j, col); }));
    if (UML[raw]) { set(x, y - 2, col); set(x + 2, y - 2, col); }
    x += 4;
  }
  return x - x0 - 1;
}
export const glyphWidth = (text) => String(text).length * 4 - 1;
